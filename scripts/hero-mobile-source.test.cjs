const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const sharp = require('sharp')
const root = path.join(__dirname, '..')
const landing = fs.readFileSync(path.join(root, 'src/components/landing/PremiumLanding.tsx'), 'utf8')
const css = fs.readFileSync(path.join(root, 'src/components/landing/premium.css'), 'utf8')
test('hero entrega arquivos distintos para celular e desktop, com prioridade de carregamento', async () => {
  assert.match(landing, /<source media="\(max-width: 700px\)" srcSet="\/uploads\/landing-v3\/hero-mobile.webp"/)
  assert.match(landing, /fetchPriority="high"/)
  for (const name of ['hero-mobile.webp','hero-studio.webp']) {
    const file=path.join(root,'public/uploads/landing-v3',name)
    const meta=await sharp(file).metadata()
    assert.equal(meta.format,'webp')
    assert.ok(fs.statSync(file).size < 200000, name+' deve permanecer abaixo de 200 KB')
    assert.ok(meta.width >= 900)
  }
})
test('animações respeitam preferência de movimento reduzido e galeria tem pausa', () => {
  assert.match(css, /@media\(prefers-reduced-motion:reduce\)/)
  assert.match(css, /animation:none!important/)
  assert.match(css, /\.cgx-marquee-viewport\{overflow-x:auto/)
  const carousel=fs.readFileSync(path.join(root,'src/components/landing/ShowcaseCarousel.tsx'),'utf8')
  assert.match(carousel, /aria-pressed=\{paused\}/)
  assert.match(carousel, /tabIndex=\{duplicate \? -1 : 0\}/)
  assert.match(carousel, /aria-labelledby="cgx-art-title"/)
})
