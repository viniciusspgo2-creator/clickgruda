const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const file = p => fs.readFileSync(path.join(root, p), 'utf8')
test('new portal and landing assets exist', () => {
  for (const f of ['public/uploads/cg-hero-mascote-cadeira-2026.webp','public/uploads/rebrand/hero-mascote-cadeira-landing-2026.webp','public/uploads/rebrand/hero-mascote-cadeira-mobile-2026.webp']) assert.ok(fs.statSync(path.join(root,f)).size > 50000, `${f} missing`)
  assert.match(file('src/components/views/PortalView.tsx'),/cg-hero-mascote-cadeira-2026.webp/)
  assert.match(file('src/components/views/LandingView.tsx'),/hero-mascote-cadeira-landing-2026.webp/)
})
test('announcement endpoints and access control exist', () => {
  assert.match(file('src/app/api/admin/announcement/route.ts'),/isAdmin\(\)/)
  assert.match(file('src/app/api/admin/announcement/route.ts'),/writeAnnouncement\(/)
  assert.match(file('src/app/api/announcement/route.ts'),/getSessionUser\(/)
  assert.match(file('src/components/views/AdminView.tsx'),/Avisos \/ Pop-up/)
  assert.match(file('src/components/views/PortalView.tsx'),/AnnouncementDialog userId/)
  assert.match(file('src/components/portal/AnnouncementDialog.tsx'),/Continuar navegando/)
})
test('studio actions do not contain oversized spanning button', () => {
  const source=file('src/components/views/PortalView.tsx')
  assert.match(source,/sm:grid-cols-3/)
  assert.doesNotMatch(source,/sm:col-span-2">Abrir Studio Mockup/)
})
